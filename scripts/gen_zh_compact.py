#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate 10 Flat Chinese (zh-CN) Docs in the Root Directory for Kyna Player"""

import os
import shutil

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS_ZH = os.path.join(BASE_DIR, 'src', 'content', 'docs', 'zh-CN')

# 1. Clean old directory contents (including subdirectories)
if os.path.exists(DOCS_ZH):
    for item in os.listdir(DOCS_ZH):
        p = os.path.join(DOCS_ZH, item)
        if os.path.isdir(p):
            shutil.rmtree(p)
        elif os.path.isfile(p):
            os.remove(p)
os.makedirs(DOCS_ZH, exist_ok=True)

def write(filename, content):
    full_path = os.path.join(DOCS_ZH, filename)
    with open(full_path, 'w', encoding='utf-8') as f:
        f.write(content.strip() + '\n')
    print(f"[zh-CN] Generated flat doc: {filename}")

